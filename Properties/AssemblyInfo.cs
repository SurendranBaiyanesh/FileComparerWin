using System.Windows;

// Assembly-level declarations that have no MSBuild property to set them.
//
// The rest of this assembly's identity - product, description, company, version, copyright - is
// declared as properties in FileComparerWindows.csproj and generated into the assembly at build
// time. Repeating any of it here would be a second copy of the same attribute, which does not
// compile, so the two halves are deliberately kept apart.

// Where WPF looks for the dictionaries that style a control the assembly does not style itself.
// This application draws no custom controls and carries no Themes\generic.xaml, so there is no
// theme-specific dictionary to find, and everything generic sits in App.xaml inside this assembly.
[assembly: ThemeInfo(ResourceDictionaryLocation.None, ResourceDictionaryLocation.SourceAssembly)]